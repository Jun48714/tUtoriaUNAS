import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const origin = 'https://raw.githubusercontent.com/FortAwesome/Font-Awesome/6.5.1';
const response = await fetch(`${origin}/metadata/icons.json`);
if (!response.ok) throw new Error(`Font Awesome metadata: ${response.status}`);
const metadata = await response.json();

/** Glifos de los `crearIcono('nombre'[, 'estilo'])` de un archivo, en orden de aparición. */
async function glifosDe(archivo) {
  const source = await readFile(resolve(root, archivo), 'utf8');
  const selected = {};
  for (const match of source.matchAll(/crearIcono\('([^']+)'(?:, '(solid|regular)')?\)/g)) {
    const [, name, style = 'solid'] = match;
    const glyph = metadata[name]?.svg?.[style];
    if (!glyph || !metadata[name].free.includes(style)) throw new Error(`Missing free icon: ${style}:${name}`);
    selected[`${style}:${name}`] = { width: glyph.width, height: glyph.height, path: glyph.path };
  }
  return selected;
}

// Dos mapas: los iconos de la pantalla de acceso van en el JavaScript inicial; el resto, con el portal.
const acceso = await glifosDe('frontend/src/components/ui/iconosAcceso.tsx');
const portal = Object.fromEntries(
  Object.entries(await glifosDe('frontend/src/components/ui/icons.tsx')).filter(([clave]) => !(clave in acceso)),
);
const tipo = 'Record<string, { width: number; height: number; path: string }>';
const cabecera = (nota) =>
  `/** Font Awesome Free 6.5.1 — official SVG paths, CC BY 4.0.\n * Source: ${origin}/metadata/icons.json\n * Generated by scripts/vendor-falcon-icons.mjs. See LICENSE-FONT-AWESOME.txt.\n${nota}\n */\n`;
const vendor = 'frontend/src/assets/vendor';
await writeFile(
  resolve(root, `${vendor}/fontawesome-acceso.ts`),
  `${cabecera(' * Glifos de la pantalla de acceso (components/ui/iconosAcceso.tsx): van en el JavaScript inicial.')}export const glifosAcceso: ${tipo} = ${JSON.stringify(acceso, null, 2)};\n`,
);
await writeFile(
  resolve(root, `${vendor}/fontawesome-icons.ts`),
  `${cabecera(' * Glifos del portal (components/ui/icons.tsx): se cargan con el portal, no con /login.')}import { glifosAcceso } from './fontawesome-acceso';\n\nexport const glifosPortal: ${tipo} = ${JSON.stringify(portal, null, 2)};\n\n/** Todos los glifos vendorizados (acceso y portal). */\nexport const fontAwesomeIcons: ${tipo} = { ...glifosAcceso, ...glifosPortal };\n`,
);
const license = await fetch(`${origin}/LICENSE.txt`);
if (!license.ok) throw new Error(`Font Awesome license: ${license.status}`);
await writeFile(resolve(root, `${vendor}/LICENSE-FONT-AWESOME.txt`), await license.text());
console.log(`Vendored ${Object.keys(acceso).length + Object.keys(portal).length} official SVG icons from Font Awesome Free 6.5.1.`);
